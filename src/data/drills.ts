import type { DrillSet, TransformationKind } from "../types";

export const levelOrder = ["A1", "A2", "B1", "B2", "C1", "C2"] as const;

type TransformSeed = [cue: string, target: string];

interface DrillSeed {
  id: string;
  title: string;
  level: (typeof levelOrder)[number];
  focus: string;
  baseSentence: string;
  substitutionSlot: string;
  cues: string[];
  makeTarget: (cue: string) => string;
  transformations: TransformSeed[];
}

const typeCycle: TransformationKind[] = [
  "negative",
  "question",
  "past",
  "future",
  "thirdPerson",
  "plural",
  "polite"
];

function makeSet(seed: DrillSeed): DrillSet {
  return {
    id: seed.id,
    title: seed.title,
    level: seed.level,
    focus: seed.focus,
    baseSentence: seed.baseSentence,
    substitutionSlot: seed.substitutionSlot,
    substitution: seed.cues.slice(0, 20).map((cue, index) => ({
      id: `s${index + 1}`,
      cue,
      target: seed.makeTarget(cue)
    })),
    transformation: seed.transformations.slice(0, 20).map(([cue, target], index) => ({
      id: `t${index + 1}`,
      type: typeCycle[index % typeCycle.length],
      cue,
      target
    }))
  };
}

function actionTransforms(base: string, past: string, third: string, soft = `would like to ${base}`): TransformSeed[] {
  return [
    ["Make it negative", `I don't ${base}.`],
    ["Make it a yes-no question", `Do I ${base}?`],
    ["Change it to past tense", `I ${past}.`],
    ["Change it to future with will", `I will ${base}.`],
    ["Change I to she", `She ${third}.`],
    ["Change I to we", `We ${base}.`],
    ["Make she negative", `She doesn't ${base}.`],
    ["Ask about she", `Does she ${base}?`],
    ["Ask in past tense", `Did I ${base}?`],
    ["Make it softer", `I ${soft}.`],
    ["Make a future question", `Will I ${base}?`],
    ["Change it to he", `He ${third}.`],
    ["Make he negative", `He doesn't ${base}.`],
    ["Change it to they", `They ${base}.`],
    ["Ask about they", `Do they ${base}?`],
    ["Change they to past tense", `They ${past}.`],
    ["Change they to future", `They will ${base}.`],
    ["Make we negative", `We don't ${base}.`],
    ["Ask about we", `Do we ${base}?`],
    ["Use have to", `I have to ${base}.`]
  ];
}

function actionSeed(options: {
  id: string;
  title: string;
  level: DrillSeed["level"];
  focus: string;
  base: string;
  past: string;
  third: string;
  substitutionSlot: string;
  cues: string[];
  makeTarget: (cue: string) => string;
  soft?: string;
}): DrillSeed {
  return {
    id: options.id,
    title: options.title,
    level: options.level,
    focus: options.focus,
    baseSentence: `I ${options.base}.`,
    substitutionSlot: options.substitutionSlot,
    cues: options.cues,
    makeTarget: options.makeTarget,
    transformations: actionTransforms(options.base, options.past, options.third, options.soft)
  };
}

function bePredicateSeed(options: {
  id: string;
  title: string;
  level: DrillSeed["level"];
  focus: string;
  basePredicate: string;
  substitutionSlot: string;
  cues: string[];
  makePredicate: (cue: string) => string;
  formal?: string;
}): DrillSeed {
  const predicate = options.basePredicate;
  return {
    id: options.id,
    title: options.title,
    level: options.level,
    focus: options.focus,
    baseSentence: `I'm ${predicate}.`,
    substitutionSlot: options.substitutionSlot,
    cues: options.cues,
    makeTarget: (cue) => `I'm ${options.makePredicate(cue)}.`,
    transformations: [
      ["Make it negative", `I'm not ${predicate}.`],
      ["Make it a yes-no question", `Am I ${predicate}?`],
      ["Change it to past", `I was ${predicate}.`],
      ["Change it to future", `I will be ${predicate}.`],
      ["Change I to she", `She is ${predicate}.`],
      ["Change I to we", `We are ${predicate}.`],
      ["Make she negative", `She isn't ${predicate}.`],
      ["Ask about she", `Is she ${predicate}?`],
      ["Ask in past tense", `Was I ${predicate}?`],
      ["Use present perfect continuous", `I have been ${predicate}.`],
      ["Use they", `They are ${predicate}.`],
      ["Make they negative", `They aren't ${predicate}.`],
      ["Ask about they", `Are they ${predicate}?`],
      ["Use might be", `I might be ${predicate}.`],
      ["Use should be", `I should be ${predicate}.`],
      ["Use used to be", `I used to be ${predicate}.`],
      ["Use still", `I'm still ${predicate}.`],
      ["Use no longer", `I'm no longer ${predicate}.`],
      ["Use more formal wording", options.formal ?? `I am ${predicate}.`],
      ["Ask why", `Why am I ${predicate}?`]
    ]
  };
}

function modalSeed(options: {
  id: string;
  title: string;
  level: DrillSeed["level"];
  focus: string;
  modal: "can" | "should";
  base: string;
  substitutionSlot: string;
  cues: string[];
  makeTarget: (cue: string) => string;
}): DrillSeed {
  const { modal, base } = options;
  const negative = modal === "can" ? "can't" : "shouldn't";
  const past = modal === "can" ? "could" : "should have";
  const future = modal === "can" ? "will be able to" : "will need to";
  return {
    id: options.id,
    title: options.title,
    level: options.level,
    focus: options.focus,
    baseSentence: `I ${modal} ${base}.`,
    substitutionSlot: options.substitutionSlot,
    cues: options.cues,
    makeTarget: options.makeTarget,
    transformations: [
      ["Make it negative", `I ${negative} ${base}.`],
      ["Make it a yes-no question", `${capitalize(modal)} I ${base}?`],
      ["Change it to past meaning", `I ${past} ${base}.`],
      ["Change it to future meaning", `I ${future} ${base}.`],
      ["Change I to she", `She ${modal} ${base}.`],
      ["Change I to we", `We ${modal} ${base}.`],
      ["Make she negative", `She ${negative} ${base}.`],
      ["Ask about she", `${capitalize(modal)} she ${base}?`],
      ["Ask about we", `${capitalize(modal)} we ${base}?`],
      ["Use might", `I might ${base}.`],
      ["Use have to", `I have to ${base}.`],
      ["Use need to", `I need to ${base}.`],
      ["Use be able to", `I am able to ${base}.`],
      ["Use not be able to", `I am not able to ${base}.`],
      ["Use they", `They ${modal} ${base}.`],
      ["Ask about they", `${capitalize(modal)} they ${base}?`],
      ["Use probably", `I probably ${modal} ${base}.`],
      ["Use definitely", `I definitely ${modal} ${base}.`],
      ["Make it polite", `Could I ${base}?`],
      ["Make it formal", `I am expected to ${base}.`]
    ]
  };
}

function itClauseSeed(options: {
  id: string;
  title: string;
  level: DrillSeed["level"];
  focus: string;
  adjective: string;
  clause: string;
  substitutionSlot: string;
  cues: string[];
}): DrillSeed {
  const { adjective, clause } = options;
  return {
    id: options.id,
    title: options.title,
    level: options.level,
    focus: options.focus,
    baseSentence: `It is ${adjective} that ${clause}.`,
    substitutionSlot: options.substitutionSlot,
    cues: options.cues,
    makeTarget: (cue) => `It is ${adjective} that ${cue}.`,
    transformations: [
      ["Make it negative", `It is not ${adjective} that ${clause}.`],
      ["Make it a question", `Is it ${adjective} that ${clause}?`],
      ["Change it to past", `It was ${adjective} that ${clause}.`],
      ["Change it to future", `It will be ${adjective} that ${clause}.`],
      ["Use seems", `It seems ${adjective} that ${clause}.`],
      ["Use appears", `It appears ${adjective} that ${clause}.`],
      ["Use may be", `It may be ${adjective} that ${clause}.`],
      ["Use might be", `It might be ${adjective} that ${clause}.`],
      ["Use highly", `It is highly ${adjective} that ${clause}.`],
      ["Use increasingly", `It is increasingly ${adjective} that ${clause}.`],
      ["Use still", `It is still ${adjective} that ${clause}.`],
      ["Use no longer", `It is no longer ${adjective} that ${clause}.`],
      ["Use probably", `It is probably ${adjective} that ${clause}.`],
      ["Use not necessarily", `It is not necessarily ${adjective} that ${clause}.`],
      ["Ask why", `Why is it ${adjective} that ${clause}?`],
      ["Ask whether", `Is it ${adjective} whether ${clause}?`],
      ["Use the fact that", `The fact that ${clause} is ${adjective}.`],
      ["Use what is", `What is ${adjective} is that ${clause}.`],
      ["Use formal style", `The ${adjective} point is that ${clause}.`],
      ["Use cautious style", `It may well be ${adjective} that ${clause}.`]
    ]
  };
}

function capitalize(value: string) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

